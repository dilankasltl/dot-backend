async function seedDatabase() {
  try {
    console.log('[SEED] Updating users with Mr. prefix and default passwords...');
    for (const u of usersData) {
      const existing = await User.findOne({ username: u.username });
      if (!existing) {
        await User.create({ ...u, defaultPassword: u.password });
      } else {
        await User.updateOne(
          { username: u.username },
          {
            $set: {
              name: u.name,
              role: u.role,
              department: u.department,
              assignedL1Approver: u.assignedL1Approver,
              approvedDepartments: u.approvedDepartments,
              canViewAllPending: u.canViewAllPending,
              canViewCharts: u.canViewCharts,
              defaultPassword: u.password // default password always stored
            }
          }
        );
      }
    }
    console.log(`[SEED] Upserted ${usersData.length} users successfully.`);

    const empCount = await Employee.countDocuments();
    if (empCount < employeesRaw.length) {
      console.log('[SEED] Seeding employees...');
      for (const emp of employeesRaw) {
        await Employee.findOneAndUpdate(
          { epfNo: emp.epfNo },
          { $set: emp },
          { upsert: true }
        );
      }
      console.log(`[SEED] Seeded ${employeesRaw.length} employees.`);
    }
  } catch (err) {
    console.error('[SEED] Error during seeding:', err);
  }
}

module.exports = { seedDatabase, usersData, employeesRaw };
